#!/usr/bin/env node
// After Effects bridge: writes an ExtendScript (.jsx) that rebuilds the composition's skeleton in AE — comp size/fps/
// duration, the rendered video as a layer, timeline labels as comp markers, and one null per tracked element carrying
// sampled position/scale/opacity keyframes (attach AE text/shape layers or effects to them).
// usage: export-ae.mjs <comp.html> --out out/film.jsx [--video out/film.mp4] [--select "[id]"] [--rate 10]
// Track: elements matching --select (default: [data-mf-export], else every #id inside #stage). Run in AE: File ▸ Scripts ▸ Run Script File.
// STATUS: generated JSX follows the documented AE scripting API but has not been run inside After Effects yet.
import fs from "node:fs";
import path from "node:path";
import { parseArgs, line, launchBrowser, serve } from "./lib/common.mjs";

const a = parseArgs();
const comp = a._[0];
if (!comp || !a.out) { console.error("usage: export-ae.mjs <comp.html> --out film.jsx [--video film.mp4] [--select css] [--rate 10]"); process.exit(1); }
const abs = path.resolve(comp), srv = await serve(path.dirname(abs)), browser = await launchBrowser();
let meta, tracks;
try {
  const p = await browser.newPage(); await p.addInitScript(() => { window.__MF_RENDER = true; });
  await p.goto(`${srv.url}/${path.basename(abs)}`); await p.waitForFunction(() => !!window.__MF); await p.evaluate(() => window.__MF.ready);
  meta = await p.evaluate(() => JSON.parse(JSON.stringify(window.__MF.meta)));
  await p.setViewportSize({ width: meta.width, height: meta.height });
  const sel = a.select || null, rate = +a.rate || 10, steps = Math.ceil(meta.duration * rate);
  tracks = {};
  for (let i = 0; i <= steps; i++) {
    const t = Math.min(meta.duration, i / rate);
    await p.evaluate((x) => window.__MF.seek(x), t);
    const snap = await p.evaluate((sel) => {
      const st = document.getElementById("stage"), sr = st.getBoundingClientRect(), k = sr.width / st.offsetWidth;
      const els = [...st.querySelectorAll(sel || "[data-mf-export]")]; const list = els.length ? els : [...st.querySelectorAll("[id]")].filter((e) => e.id !== "stage");
      return list.slice(0, 60).map((e) => { const r = e.getBoundingClientRect(); let o = 1; for (let n = e; n && n !== document.body; n = n.parentElement) o *= +getComputedStyle(n).opacity;
        return { id: e.id || e.className || e.tagName, x: (r.left + r.width / 2 - sr.left) / k, y: (r.top + r.height / 2 - sr.top) / k, w: r.width / k, h: r.height / k, o }; });
    }, sel);
    for (const s of snap) (tracks[s.id] ||= []).push({ t, ...s });
  }
} finally { await browser.close(); await srv.close(); }

const q = (s) => JSON.stringify(String(s));
const video = a.video ? path.resolve(a.video).replace(/\\/g, "/") : null;
let jsx = `// generated by motion-forge export-ae.mjs from ${path.basename(comp)}
(function () {
  app.beginUndoGroup("motion-forge import");
  var comp = app.project.items.addComp(${q(meta.title || path.basename(comp))}, ${meta.width}, ${meta.height}, 1, ${meta.duration}, ${meta.fps});
`;
if (video) jsx += `  var f = new File(${q(video)}); if (f.exists) { var item = app.project.importFile(new ImportOptions(f)); comp.layers.add(item); }\n`;
for (const [name, t] of Object.entries(meta.labels || {})) jsx += `  comp.markerProperty.setValueAtTime(${t}, new MarkerValue(${q(name)}));\n`;
for (const [id, ks] of Object.entries(tracks)) {
  const moves = ks.some((k) => Math.abs(k.x - ks[0].x) > 0.5 || Math.abs(k.y - ks[0].y) > 0.5 || Math.abs(k.o - ks[0].o) > 0.01 || Math.abs(k.w - ks[0].w) > 0.5);
  if (!moves) continue;   // static elements are already in the video; only animated ones become nulls
  jsx += `  (function () { var n = comp.layers.addNull(); n.name = ${q("mf:" + id)};
    var P = n.property("ADBE Transform Group").property("ADBE Position"), S = n.property("ADBE Transform Group").property("ADBE Scale"), O = n.property("ADBE Transform Group").property("ADBE Opacity");
    P.setValuesAtTimes([${ks.map((k) => k.t.toFixed(3)).join(",")}], [${ks.map((k) => `[${k.x.toFixed(1)},${k.y.toFixed(1)}]`).join(",")}]);
    S.setValuesAtTimes([${ks.map((k) => k.t.toFixed(3)).join(",")}], [${ks.map((k) => { const s = ks[0].w ? (100 * k.w) / ks[0].w : 100; return `[${s.toFixed(1)},${s.toFixed(1)}]`; }).join(",")}]);
    O.setValuesAtTimes([${ks.map((k) => k.t.toFixed(3)).join(",")}], [${ks.map((k) => (k.o * 100).toFixed(1)).join(",")}]); })();
`;
}
jsx += `  comp.openInViewer(); app.endUndoGroup();\n})();\n`;
fs.mkdirSync(path.dirname(path.resolve(a.out)), { recursive: true });
fs.writeFileSync(path.resolve(a.out), jsx);
line(`PASS export-ae ${path.basename(comp)} → ${path.relative(process.cwd(), path.resolve(a.out))} (${Object.keys(meta.labels || {}).length} markers, ${(jsx.match(/addNull/g) || []).length} animated nulls${video ? ", video layer" : ""}) — untested inside AE`);
