#!/usr/bin/env node
// "Pick your favourite": render the same composition in N art directions (palette + type emphasis) as labelled stills
// side by side, in about a minute — choose one, then apply it.
//   directions.mjs <comp.html> [--n 4] [--times auto|1.5,4] [--out <dir>/out/directions]
//   directions.mjs <comp.html> --apply <name>        write that direction into <dir>/brand.css
// Works with every template that reads --mf-* variables (all except the deliberately dark-native 3D ones keep their sky).
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { parseArgs, line, SKILL_DIR } from "./lib/common.mjs";

const PACKS = {
  editorial: { ground: "#F2EEE5", ink: "#18171A", mute: "#6B6862", signal: "#D9442B", display: "MF Display", text: "MF Text", note: "warm paper, red accent" },
  night:     { ground: "#0E1320", ink: "#F3EEE3", mute: "#9AA3B5", signal: "#FFB547", display: "MF Display", text: "MF Text", note: "midnight, amber accent" },
  electric:  { ground: "#0B0B0C", ink: "#FFFFFF", mute: "#A3A3A8", signal: "#C6FF3D", display: "MF Display", text: "MF Text", note: "black, electric lime" },
  pastel:    { ground: "#EFE6FA", ink: "#2A1840", mute: "#5E4F73", signal: "#E2583E", display: "MF Serif", text: "MF Text", note: "lilac, serif display" },
  swiss:     { ground: "#FFFFFF", ink: "#111111", mute: "#5F5F5F", signal: "#0047FF", display: "MF Display", text: "MF Text", note: "white, Swiss blue" },
  forest:    { ground: "#12261E", ink: "#EEF3E8", mute: "#9DB3A6", signal: "#F0C24B", display: "MF Serif", text: "MF Text", note: "deep green, gold, serif" },
};
const a = parseArgs();
const comp = path.resolve(a._[0] || "");
if (!a._[0] || !fs.existsSync(comp)) { console.error("usage: directions.mjs <comp.html> [--n 4] [--times auto] | --apply <name>"); process.exit(1); }
const dir = path.dirname(comp);
const css = (p) => `/* direction pack — generated by directions.mjs */\n:root, #stage {\n  --mf-ground: ${p.ground};\n  --mf-ink: ${p.ink};\n  --mf-mute: ${p.mute};\n  --mf-signal: ${p.signal};\n  --mf-font-display: "${p.display}";\n  --mf-font-text: "${p.text}";\n}\n`;
if (a.apply) {
  const p = PACKS[a.apply]; if (!p) { console.error("unknown direction: " + a.apply + " (" + Object.keys(PACKS).join(", ") + ")"); process.exit(1); }
  const bc = path.join(dir, "brand.css"); if (fs.existsSync(bc)) fs.copyFileSync(bc, bc + ".bak");
  fs.writeFileSync(bc, css(p)); line(`applied direction ${a.apply} → ${path.relative(process.cwd(), bc)} (previous kept as brand.css.bak)`); process.exit(0);
}
const names = Object.keys(PACKS).slice(0, Math.max(2, Math.min(6, +a.n || 4)));
const out = path.resolve(a.out || path.join(dir, "out", "directions")); fs.mkdirSync(out, { recursive: true });
const tmp = fs.mkdtempSync(path.join((await import("node:os")).tmpdir(), "mf-directions-"));   // outside the project (copying a dir into itself fails)
const rows = [];
for (const n of names) {
  const d = path.join(tmp, n);
  fs.cpSync(dir, d, { recursive: true, filter: (s) => !/[\\/]out([\\/]|$)/.test(s.slice(dir.length)) });
  fs.writeFileSync(path.join(d, "brand.css"), css(PACKS[n]));
  const r = spawnSync(process.execPath, [path.join(SKILL_DIR, "scripts", "render.mjs"), path.join(d, path.basename(comp)), "--stills", String(a.times || "auto"), "--score", "--no-determinism", "--thumb", "320", "--outdir", path.join(d, "frames")], { encoding: "utf8" });
  const rep = JSON.parse(fs.readFileSync(path.join(d, "frames", "report.json"), "utf8"));
  const frames = fs.readdirSync(path.join(d, "frames")).filter((f) => /^\d\d_.*\.png$/.test(f)).sort();
  const pick = a.times ? frames : [frames[Math.floor(frames.length * 0.35)], frames[Math.floor(frames.length * 0.75)]].filter(Boolean);
  rows.push({ n, verdict: rep.verdict, issues: rep.issues.length, files: pick.map((f) => path.join(d, "frames", f)) });
  line(`  ${rep.verdict} ${n.padEnd(9)} ${PACKS[n].note}${rep.issues.length ? " — " + rep.issues.slice(0, 2).map((i) => i.code).join(", ") : ""}`);
}
// grid: one row per direction, labelled
const inputs = rows.flatMap((r) => r.files.flatMap((f) => ["-i", f]));
let k = 0; const per = rows[0].files.length, parts = [], rowsOut = [];
rows.forEach((r, ri) => { const ids = r.files.map(() => { const id = `v${k}`; parts.push(`[${k}:v]scale=480:-2[${id}]`); k++; return `[${id}]`; });
  parts.push(`${ids.join("")}${per > 1 ? `hstack=inputs=${per}` : "null"},drawtext=text='${ri + 1}  ${r.n}':x=12:y=12:fontsize=26:fontcolor=white:box=1:boxcolor=black@0.7:boxborderw=8[r${ri}]`); rowsOut.push(`[r${ri}]`); });
parts.push(`${rowsOut.join("")}vstack=inputs=${rows.length}[o]`);
const sheet = path.join(out, "directions.png");
let r = spawnSync("ffmpeg", ["-y", "-loglevel", "error", ...inputs, "-filter_complex", parts.join(";"), "-map", "[o]", sheet], { encoding: "utf8" });
if (r.status !== 0) r = spawnSync("ffmpeg", ["-y", "-loglevel", "error", ...inputs, "-filter_complex", parts.join(";").replace(/,drawtext=[^\[]*(\[r\d+\])/g, "$1"), "-map", "[o]", sheet], { encoding: "utf8" });
for (const row of rows) row.files.forEach((f, i) => fs.copyFileSync(f, path.join(out, `${row.n}_${i + 1}.png`)));
fs.rmSync(tmp, { recursive: true, force: true });
line(`${r.status === 0 ? "PASS" : "FAIL"} directions ${names.length} → ${path.relative(process.cwd(), sheet)}   apply: directions.mjs ${path.relative(process.cwd(), comp)} --apply <name>`);
